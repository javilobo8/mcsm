package spec

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Modpack platforms. The image TYPE is the platform itself: itzg
// (scripts/start-configuration) copies TYPE=MODRINTH|AUTO_CURSEFORGE|FTBA to
// MODPACK_PLATFORM, and also emitting MODPACK_PLATFORM with TYPE≠VANILLA only
// produces the warning "Avoid setting TYPE and MODPACK_PLATFORM". That is why it is not emitted.
const (
	PlatformModrinth       = "MODRINTH"
	PlatformAutoCurseForge = "AUTO_CURSEFORGE"
	PlatformFTBA           = "FTBA"
)

// ModpackPlatforms are the valid values of modpack.platform (and of type with a modpack).
var ModpackPlatforms = map[string]bool{PlatformModrinth: true, PlatformAutoCurseForge: true, PlatformFTBA: true}

// ModrinthLoaders are the MODRINTH_LOADER values mc-image-helper accepts ("" = not set).
var ModrinthLoaders = map[string]bool{"": true, "fabric": true, "forge": true, "quilt": true, "neoforge": true}

var (
	// listEntryRe: printable ASCII without spaces or commas (lists are joined with commas).
	// The same pattern is in zod; do not use \s, which does not mean the same in Go (RE2) and in JS.
	listEntryRe = regexp.MustCompile(`^[!-+\--~]{1,300}$`)
	urlRe       = regexp.MustCompile(`^https?://[!-+\--~]{1,1000}$`)
	digitsRe    = regexp.MustCompile(`^[0-9]{1,12}$`)
	// playerRe: Java profile name (1-16 letters, digits or _) or UUID with or without dashes.
	playerRe = regexp.MustCompile(`^([A-Za-z0-9_]{1,16}|[0-9a-fA-F]{8}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{4}-?[0-9a-fA-F]{12})$`)
	// cfAPIKeyRe: the CurseForge API key (bcrypt's $2a$10$…): printable ASCII without spaces.
	// Same regex as CURSEFORGE_API_KEY_RE in the panel.
	cfAPIKeyRe = regexp.MustCompile(`^[!-~]{1,200}$`)
)

// whitelistProps are managed by the whitelist section through env; they cannot also go in properties.
var whitelistProps = []string{"white-list", "enforce-whitelist"}

// Variables generated by the Players sections. With the section present, the free-form env (which
// wins over what is generated) cannot set them: revoking an op or a player would have no effect and the UI
// would say otherwise. EXISTING_*_FILE is allowed (MERGE is a conscious choice).
// Same messages as envSectionConflicts in the panel.
var (
	opsEnv       = []string{"OPS", "OPS_FILE"}
	whitelistEnv = []string{"WHITELIST", "WHITELIST_FILE", "ENABLE_WHITELIST"}
)

func (s Spec) validateSectionEnv() error {
	check := func(keys []string, what string) error {
		for _, k := range keys {
			if _, ok := s.Env[k]; ok {
				return fmt.Errorf("spec: Remove the %s variable from the environment variables (Advanced): %s in the Players section", k, what)
			}
		}
		return nil
	}
	if s.Ops != nil {
		if err := check(opsEnv, "operators are managed"); err != nil {
			return err
		}
	}
	if s.Whitelist != nil {
		return check(whitelistEnv, "the whitelist is managed")
	}
	return nil
}

type Modpack struct {
	Platform  string `json:"platform"`
	SlugOrURL string `json:"slugOrUrl"`
	VersionID string `json:"versionId"`
	Loader    string `json:"loader"`
}

type ModSources struct {
	ModrinthProjects []string `json:"modrinthProjects"`
	CurseforgeFiles  []string `json:"curseforgeFiles"`
	URLs             []string `json:"urls"`
}

type PluginSources struct {
	ModrinthProjects []string `json:"modrinthProjects"`
	SpigetResources  []string `json:"spigetResources"`
	URLs             []string `json:"urls"`
	// CurseforgeFiles: Bukkit plugins from CurseForge (slug or projectId:fileId). Shares
	// CURSEFORGE_FILES with mods; omitempty keeps the hash of specs without it.
	CurseforgeFiles []string `json:"curseforgeFiles,omitempty"`
}

// DatapackSources: Modrinth datapacks. Each entry travels in MODRINTH_PROJECTS with the
// "datapack:" prefix, which makes itzg install it into <level>/datapacks.
type DatapackSources struct {
	ModrinthProjects []string `json:"modrinthProjects"`
}

const datapackPrefix = "datapack:"

// datapackEntry adds the "datapack:" prefix unless the entry already has it.
func datapackEntry(e string) string {
	if strings.HasPrefix(e, datapackPrefix) {
		return e
	}
	return datapackPrefix + e
}

type Whitelist struct {
	Enabled bool     `json:"enabled"`
	Players []string `json:"players"`
}

type listRule struct {
	name  string
	items []string
	re    *regexp.Regexp
}

// UsesCurseForge reports whether the spec downloads anything from CurseForge (and therefore receives CF_API_KEY).
func (s Spec) UsesCurseForge() bool {
	return (s.Modpack != nil && s.Modpack.Platform == PlatformAutoCurseForge) ||
		(s.Mods != nil && len(s.Mods.CurseforgeFiles) > 0) ||
		(s.Plugins != nil && len(s.Plugins.CurseforgeFiles) > 0)
}

// levelNameErr: level-name is the world folder inside /data. No separators or "..": today it only
// affects the container, but a plan that builds host paths with it (world reset or upload,
// backups) must not be able to escape. Same message as in zod (contentCheck).
const levelNameErr = "The level-name property is the world folder: it cannot contain “/”, “\\” or “..”"

func validLevelName(v string) bool {
	return !strings.ContainsAny(v, `/\`) && !strings.Contains(v, "..")
}

func (s Spec) validateContent() error {
	// Without repeating the value: the error ends up in observed.error, which the browser sees.
	if s.CurseForgeAPIKey != "" && !cfAPIKeyRe.MatchString(s.CurseForgeAPIKey) {
		return fmt.Errorf("spec: the CurseForge API key is not valid (1-200 printable ASCII characters, no spaces); change it in the panel")
	}
	if err := s.validateModpack(); err != nil {
		return err
	}
	if v, ok := s.Properties["level-name"]; ok && !validLevelName(v) {
		return fmt.Errorf("spec: %s", levelNameErr)
	}
	var rules []listRule
	if s.Mods != nil {
		rules = append(rules,
			listRule{"mods.modrinthProjects", s.Mods.ModrinthProjects, listEntryRe},
			listRule{"mods.curseforgeFiles", s.Mods.CurseforgeFiles, listEntryRe},
			listRule{"mods.urls", s.Mods.URLs, urlRe})
	}
	if s.Plugins != nil {
		rules = append(rules,
			listRule{"plugins.modrinthProjects", s.Plugins.ModrinthProjects, listEntryRe},
			listRule{"plugins.spigetResources", s.Plugins.SpigetResources, digitsRe},
			listRule{"plugins.urls", s.Plugins.URLs, urlRe},
			listRule{"plugins.curseforgeFiles", s.Plugins.CurseforgeFiles, listEntryRe})
	}
	if s.Datapacks != nil {
		rules = append(rules, listRule{"datapacks.modrinthProjects", s.Datapacks.ModrinthProjects, listEntryRe})
	}
	rules = append(rules, listRule{"ops", s.Ops, playerRe})
	if s.Whitelist != nil {
		rules = append(rules, listRule{"whitelist.players", s.Whitelist.Players, playerRe})
		for _, k := range whitelistProps {
			if _, ok := s.Properties[k]; ok {
				return fmt.Errorf("spec: the %s property is managed from the whitelist section", k)
			}
		}
	}
	for _, r := range rules {
		for _, it := range r.items {
			if !r.re.MatchString(it) {
				return fmt.Errorf("spec: invalid entry in %s: %q", r.name, it)
			}
		}
	}
	return s.validateSectionEnv()
}

func (s Spec) validateModpack() error {
	mp := s.Modpack
	if mp == nil {
		if ModpackPlatforms[s.Type] {
			return fmt.Errorf("spec: type %s requires a modpack", s.Type)
		}
		return nil
	}
	if !ModpackPlatforms[mp.Platform] {
		return fmt.Errorf("spec: invalid modpack.platform %q (MODRINTH|AUTO_CURSEFORGE|FTBA)", mp.Platform)
	}
	if s.Type != mp.Platform {
		return fmt.Errorf("spec: a %s modpack requires type=%s (current type %q)", mp.Platform, mp.Platform, s.Type)
	}
	if !listEntryRe.MatchString(mp.SlugOrURL) {
		return fmt.Errorf("spec: modpack.slugOrUrl is required, without spaces or commas")
	}
	if mp.VersionID != "" && !listEntryRe.MatchString(mp.VersionID) {
		return fmt.Errorf("spec: invalid modpack.versionId %q", mp.VersionID)
	}
	if mp.Platform != PlatformModrinth && mp.Loader != "" {
		return fmt.Errorf("spec: modpack.loader is only chosen for Modrinth modpacks")
	}
	switch mp.Platform {
	case PlatformModrinth:
		if !ModrinthLoaders[mp.Loader] {
			return fmt.Errorf("spec: invalid modpack.loader %q (fabric|forge|quilt|neoforge)", mp.Loader)
		}
	case PlatformAutoCurseForge:
		if mp.VersionID != "" && !digitsRe.MatchString(mp.VersionID) {
			return fmt.Errorf("spec: on CurseForge modpack.versionId is the file's numeric id")
		}
	case PlatformFTBA:
		if !digitsRe.MatchString(mp.SlugOrURL) || (mp.VersionID != "" && !digitsRe.MatchString(mp.VersionID)) {
			return fmt.Errorf("spec: FTB modpacks are specified by their numeric id (and numeric version)")
		}
	}
	return nil
}

// contentEnv adds to m the itzg variables for modpack, mods, plugins, whitelist and ops.
// An absent section emits nothing: specs prior to this plan keep their hash.
func (s Spec) contentEnv(m map[string]string) {
	if mp := s.Modpack; mp != nil {
		switch mp.Platform {
		case PlatformModrinth:
			m["MODRINTH_MODPACK"] = mp.SlugOrURL
			setIf(m, "MODRINTH_VERSION", mp.VersionID)
			setIf(m, "MODRINTH_LOADER", mp.Loader)
		case PlatformAutoCurseForge:
			if strings.HasPrefix(mp.SlugOrURL, "http://") || strings.HasPrefix(mp.SlugOrURL, "https://") {
				m["CF_PAGE_URL"] = mp.SlugOrURL
			} else {
				m["CF_SLUG"] = mp.SlugOrURL
			}
			setIf(m, "CF_FILE_ID", mp.VersionID)
		case PlatformFTBA:
			m["FTB_MODPACK_ID"] = mp.SlugOrURL
			setIf(m, "FTB_MODPACK_VERSION_ID", mp.VersionID)
		}
	}
	if s.Mods != nil || s.Plugins != nil || s.Datapacks != nil {
		var mods, plugins, datapacks, cfMods, cfPlugins []string
		if s.Mods != nil {
			mods, cfMods = s.Mods.ModrinthProjects, s.Mods.CurseforgeFiles
		}
		if s.Plugins != nil {
			plugins, cfPlugins = s.Plugins.ModrinthProjects, s.Plugins.CurseforgeFiles
		}
		if s.Datapacks != nil {
			for _, e := range s.Datapacks.ModrinthProjects {
				datapacks = append(datapacks, datapackEntry(e))
			}
		}
		// With the section present it is emitted even if empty: itzg then deletes what it
		// installed from Modrinth (removing the last mod in the UI removes it from the server).
		m["MODRINTH_PROJECTS"] = joinList(mods, plugins, datapacks)
		if s.Mods != nil || s.Plugins != nil {
			setIf(m, "CURSEFORGE_FILES", joinList(cfMods, cfPlugins))
		}
	}
	if s.Mods != nil {
		setIf(m, "MODS", joinList(s.Mods.URLs))
	}
	if s.Plugins != nil {
		setIf(m, "SPIGET_RESOURCES", joinList(s.Plugins.SpigetResources))
		setIf(m, "PLUGINS", joinList(s.Plugins.URLs))
	}
	if w := s.Whitelist; w != nil {
		if w.Enabled {
			m["ENABLE_WHITELIST"] = "true"
			// Section present: the panel is the source of truth even if the list ends up empty
			// (removing the last player must empty the file; without SYNCHRONIZE itzg keeps it).
			m["WHITELIST"] = joinPlayers(w.Players)
			m["EXISTING_WHITELIST_FILE"] = "SYNCHRONIZE"
		} else {
			// Explicit: without this, a whitelist enabled earlier would stay active in server.properties.
			m["ENABLE_WHITELIST"] = "false"
		}
	}
	// Ops: nil = absent (nothing is emitted); present (even if empty) synchronizes the file,
	// so that revoking the last op removes their permission.
	if s.Ops != nil {
		m["OPS"] = joinPlayers(s.Ops)
		m["EXISTING_OPS_FILE"] = "SYNCHRONIZE"
	}
	if s.CurseForgeAPIKey != "" && s.UsesCurseForge() {
		m["CF_API_KEY"] = s.CurseForgeAPIKey
	}
}

// datapacksEnv: with datapacks, itzg must know the world folder to install them into
// (<level>/datapacks); LEVEL comes from the level-name property. The free-form env wins (applied after).
func (s Spec) datapacksEnv(m map[string]string) {
	if s.Datapacks != nil {
		setIf(m, "LEVEL", s.Properties["level-name"])
	}
}

func setIf(m map[string]string, k, v string) {
	if v != "" {
		m[k] = v
	}
}

// joinList joins the lists without duplicates and sorted, separated by commas: reordering in the
// UI does not change the env (nor the hash, nor recreate the container).
func joinList(lists ...[]string) string {
	seen := map[string]bool{}
	var out []string
	for _, l := range lists {
		for _, it := range l {
			if !seen[it] {
				seen[it] = true
				out = append(out, it)
			}
		}
	}
	sort.Strings(out)
	return strings.Join(out, ",")
}

// joinPlayers like joinList but case-insensitive (Minecraft names are not
// case-sensitive): the first variant in ASCII order is kept.
func joinPlayers(list []string) string {
	out := append([]string{}, list...)
	sort.Strings(out)
	seen := map[string]bool{}
	res := out[:0]
	for _, it := range out {
		k := strings.ToLower(it)
		if !seen[k] {
			seen[k] = true
			res = append(res, it)
		}
	}
	return strings.Join(res, ",")
}
