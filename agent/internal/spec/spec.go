// Package spec defines a server's specification and its deterministic
// translation to a Docker container configuration.
package spec

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"

	units "github.com/docker/go-units"
	"github.com/moby/moby/api/types/container"
	"github.com/moby/moby/api/types/mount"
	"github.com/moby/moby/api/types/network"
)

const (
	LabelManaged  = "mcsm.managed"
	LabelServerID = "mcsm.server_id"
	LabelSlug     = "mcsm.slug"
	LabelVersion  = "mcsm.spec_version"
	LabelHash     = "mcsm.spec_hash"

	Image    = "itzg/minecraft-server"
	GamePort = 25565
	RconPort = 25575

	// PidsLimit bounds the container's processes and threads (modded servers use
	// hundreds of threads and pids counts them): a fork bomb does not exhaust the node.
	PidsLimit = 4096
	// memHeadroom is the margin over `memory` (JVM heap) when there is no memLimit:
	// the default limit is memory + 1G (spec §4.1).
	memHeadroom = 1 << 30
)

// Container hardening. CapAdd is the minimum with which itzg's entrypoint
// (chown of /data and switch to uid 1000 with no-new-privileges) starts and reaches healthy;
// tested against the real image. The itzg features that need NET_RAW/NET_ADMIN
// (autopause/autostop with knockd) are not supported.
var (
	securityOpt = []string{"no-new-privileges:true"}
	capDrop     = []string{"ALL"}
	capAdd      = []string{"CHOWN", "DAC_OVERRIDE", "FOWNER", "SETGID", "SETUID"}
)

// ReservedEnv are variables generated by the agent that `env` cannot override.
var ReservedEnv = map[string]bool{
	"EULA": true, "TYPE": true, "VERSION": true, "MEMORY": true, "ENABLE_RCON": true,
	"RCON_PASSWORD": true, "RCON_PORT": true, "SERVER_PORT": true, "CUSTOM_SERVER_PROPERTIES": true,
	"CF_API_KEY": true,
}

var slugRe = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,39}$`)

// sizeRe accepts memory sizes in whole, positive MiB or GiB (512M, 4G).
var sizeRe = regexp.MustCompile(`^[1-9]\d*[MmGg]$`)

// envNameRe validates env variable names (they cannot contain = or spaces).
var envNameRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// imageTagRe validates the itzg image tag (Docker tag grammar, without
// digest). Same regex as the panel's zod. Without it, moby cleans `..` when building the
// ImageInspect URL and a tag like "x/../../containers/<id>" reached another API.
var imageTagRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$`)

// propKeyRe validates server.properties keys.
var propKeyRe = regexp.MustCompile(`^[a-z0-9][a-z0-9._-]*$`)

// ReservedProps are server.properties keys managed by the image from
// the reserved variables; the user cannot set them.
var ReservedProps = map[string]bool{
	"server-port": true, "enable-rcon": true, "rcon.port": true, "rcon.password": true,
}

var restartPolicies = map[string]container.RestartPolicyMode{
	"":               container.RestartPolicyUnlessStopped,
	"unless-stopped": container.RestartPolicyUnlessStopped,
	"always":         container.RestartPolicyAlways,
	"no":             container.RestartPolicyDisabled,
	"on-failure":     container.RestartPolicyOnFailure,
}

type Spec struct {
	ImageTag      string            `json:"imageTag"`
	Type          string            `json:"type"`
	Version       string            `json:"version"`
	Memory        string            `json:"memory"`
	Properties    map[string]string `json:"properties"`
	Env           map[string]string `json:"env"`
	Ports         Ports             `json:"ports"`
	Resources     Resources         `json:"resources"`
	RestartPolicy string            `json:"restartPolicy"`
	RconPassword  string            `json:"rconPassword"`
	// ── plan-2 ──
	// ── plan-3 ──
	// Content sections: nil = absent (nothing is emitted and the hash does not change).
	Modpack   *Modpack       `json:"modpack,omitempty"`
	Mods      *ModSources    `json:"mods,omitempty"`
	Plugins   *PluginSources `json:"plugins,omitempty"`
	Whitelist *Whitelist     `json:"whitelist,omitempty"`
	// nil = absent; [] = present and empty (omitzero keeps the difference when serializing).
	Ops []string `json:"ops,omitzero"`
	// CurseForgeAPIKey is added by the panel when sending the spec to the agent. It is never stored in the
	// panel's spec nor travels to the browser.
	CurseForgeAPIKey string `json:"curseforgeApiKey,omitempty"`
	// ── plan-4 ──
	Backups *Backups `json:"backups,omitempty"`
	// ── plan-5 ──
	// ── plan-6 ──
	// DataPath: host folder mounted at /data instead of <DATA_ROOT>/<slug>/data (imported servers
	// with data outside DATA_ROOT). Empty = default path: container and hash do not change.
	DataPath string `json:"dataPath,omitempty"`
	// Adopt is added by the panel when sending an imported server's spec; it does not go into the container or the hash.
	Adopt *Adopt `json:"adopt,omitempty"`
	// ── plan-7 ──
	// ── plan-8 ──
	// Router: entry by hostname through the node's mc-router. nil = absent (hash unchanged).
	Router *Router `json:"router,omitempty"`
	// ── plan-9 ──
	// ── plan-10 ──
	// Build: build or loader version (PAPER_BUILD, FABRIC_LOADER_VERSION…). Empty = the latest:
	// it does not go into the environment and the hash does not change.
	Build string `json:"build,omitempty"`
}

type Ports struct {
	Game  int           `json:"game"`
	Extra []PortMapping `json:"extra"`
	// Rcon is the host TCP port that publishes the container's RCON (25575); 0 = not published.
	Rcon int `json:"rcon,omitempty"`
}

type PortMapping struct {
	Host      int    `json:"host"`
	Container int    `json:"container"`
	Proto     string `json:"proto"`
	Label     string `json:"label"`
}

type Resources struct {
	Cpus     float64 `json:"cpus"`
	MemLimit string  `json:"memLimit"`
}

type Meta struct {
	ServerID string
	Slug     string
	Version  uint64
}

type Build struct {
	Name       string
	Config     *container.Config
	HostConfig *container.HostConfig
	Networking *network.NetworkingConfig
	DataDir    string
	Hash       string
}

func Parse(b []byte) (Spec, error) {
	var s Spec
	if err := json.Unmarshal(b, &s); err != nil {
		return Spec{}, fmt.Errorf("invalid spec JSON: %w", err)
	}
	return s, s.Validate()
}

func (s Spec) Validate() error {
	if s.ImageTag != "" && !imageTagRe.MatchString(s.ImageTag) { // empty = latest
		return fmt.Errorf("spec: invalid imageTag %q (letters, digits, . _ -; starts with a letter or digit; max. 128)", s.ImageTag)
	}
	if s.Type == "" {
		return fmt.Errorf("spec: type is required")
	}
	if s.Version == "" {
		return fmt.Errorf("spec: version is required")
	}
	if !sizeRe.MatchString(s.Memory) {
		return fmt.Errorf("spec: invalid memory %q (format NNM or NNG, not 0)", s.Memory)
	}
	memBytes, err := units.RAMInBytes(s.Memory)
	if err != nil || memBytes <= 0 {
		return fmt.Errorf("spec: invalid memory %q", s.Memory)
	}
	if s.Resources.MemLimit != "" {
		if !sizeRe.MatchString(s.Resources.MemLimit) {
			return fmt.Errorf("spec: invalid memLimit %q (format NNM or NNG, not 0)", s.Resources.MemLimit)
		}
		lim, err := units.RAMInBytes(s.Resources.MemLimit)
		if err != nil || lim <= 0 {
			return fmt.Errorf("spec: invalid memLimit %q", s.Resources.MemLimit)
		}
		if lim < memBytes {
			return fmt.Errorf("spec: memLimit (%s) cannot be less than memory (%s)", s.Resources.MemLimit, s.Memory)
		}
	}
	if s.Resources.Cpus < 0 {
		return fmt.Errorf("spec: cpus cannot be negative")
	}
	if !validPort(s.Ports.Game) {
		return fmt.Errorf("spec: game port out of range: %d", s.Ports.Game)
	}
	for _, pm := range s.Ports.Extra {
		if !validPort(pm.Host) || !validPort(pm.Container) {
			return fmt.Errorf("spec: extra port out of range: %+v", pm)
		}
		if pm.Proto != "tcp" && pm.Proto != "udp" {
			return fmt.Errorf("spec: invalid proto %q (tcp|udp)", pm.Proto)
		}
		if pm.Container == RconPort {
			return fmt.Errorf("spec: the extra port cannot publish RCON (%d)", RconPort)
		}
	}
	if s.Ports.Rcon != 0 {
		if !validPort(s.Ports.Rcon) {
			return fmt.Errorf("spec: rcon port out of range: %d", s.Ports.Rcon)
		}
		if s.Ports.Rcon == s.Ports.Game {
			return fmt.Errorf("spec: the rcon port (%d) cannot be the game port", s.Ports.Rcon)
		}
		for _, pm := range s.Ports.Extra {
			if pm.Host == s.Ports.Rcon {
				return fmt.Errorf("spec: the rcon port (%d) is already used by an extra port", s.Ports.Rcon)
			}
		}
	}
	if len(s.RconPassword) < 8 {
		return fmt.Errorf("spec: rconPassword must be at least 8 characters")
	}
	if _, ok := restartPolicies[s.RestartPolicy]; !ok {
		return fmt.Errorf("spec: invalid restartPolicy %q", s.RestartPolicy)
	}
	for k := range s.Env {
		if !envNameRe.MatchString(k) {
			return fmt.Errorf("spec: invalid variable name %q", k)
		}
		if ReservedEnv[k] {
			return fmt.Errorf("spec: the variable %s is reserved and cannot be overridden", k)
		}
	}
	for k, v := range s.Properties {
		if !propKeyRe.MatchString(k) {
			return fmt.Errorf("spec: invalid property name %q", k)
		}
		if ReservedProps[k] {
			return fmt.Errorf("spec: the property %s is reserved (managed by the agent)", k)
		}
		if strings.ContainsAny(v, "\r\n") {
			return fmt.Errorf("spec: the property %s cannot have line breaks in its value", k)
		}
	}
	// ── plan-2 ──
	// ── plan-3 ──
	if err := s.validateContent(); err != nil {
		return err
	}
	if err := s.validateLimits(); err != nil {
		return err
	}
	// ── plan-4 ──
	if err := s.Backups.Validate(); err != nil {
		return err
	}
	// ── plan-5 ──
	// ── plan-6 ──
	if err := s.validateImport(); err != nil {
		return err
	}
	// ── plan-7 ──
	// ── plan-8 ──
	if err := s.Router.Validate(); err != nil {
		return err
	}
	// ── plan-9 ──
	// ── plan-10 ──
	if err := s.validateBuild(); err != nil {
		return err
	}
	return nil
}

func validPort(p int) bool { return p >= 1 && p <= 65535 }

// ValidSlug reports whether slug is a valid server slug (safe as a directory name).
func ValidSlug(slug string) bool { return slugRe.MatchString(slug) }

func ContainerName(slug string) string { return "mcsm-" + slug }

// BuildContainer translates the spec into a container configuration. It is a
// pure function: same input, same output, same Hash.
func BuildContainer(meta Meta, s Spec, dataRoot, networkName string) (*Build, error) {
	if !ValidSlug(meta.Slug) {
		return nil, fmt.Errorf("invalid slug %q", meta.Slug)
	}
	if err := s.Validate(); err != nil {
		return nil, err
	}
	tag := s.ImageTag
	if tag == "" {
		tag = "latest"
	}
	// plan-6: dataPath of imported servers.
	dataDir, err := s.dataDir(meta.Slug, dataRoot)
	if err != nil {
		return nil, err
	}
	name := ContainerName(meta.Slug)

	exposed := network.PortSet{}
	bindings := network.PortMap{}
	game := mustPort(fmt.Sprintf("%d/tcp", GamePort))
	exposed[game] = struct{}{}
	bindings[game] = []network.PortBinding{{HostPort: strconv.Itoa(s.Ports.Game)}}
	for _, pm := range s.Ports.Extra {
		p := mustPort(fmt.Sprintf("%d/%s", pm.Container, pm.Proto))
		exposed[p] = struct{}{}
		bindings[p] = append(bindings[p], network.PortBinding{HostPort: strconv.Itoa(pm.Host)})
	}
	if s.Ports.Rcon != 0 {
		rcon := mustPort(fmt.Sprintf("%d/tcp", RconPort))
		exposed[rcon] = struct{}{}
		bindings[rcon] = []network.PortBinding{{HostPort: strconv.Itoa(s.Ports.Rcon)}}
	}

	cfg := &container.Config{
		Image:        Image + ":" + tag,
		Env:          s.envList(),
		Tty:          true,
		OpenStdin:    true,
		ExposedPorts: exposed,
		Labels: map[string]string{
			LabelManaged:  "true",
			LabelServerID: meta.ServerID,
			LabelSlug:     meta.Slug,
		},
	}
	host := &container.HostConfig{
		PortBindings:  bindings,
		RestartPolicy: container.RestartPolicy{Name: restartPolicies[s.RestartPolicy]},
		SecurityOpt:   append([]string(nil), securityOpt...),
		CapDrop:       append([]string(nil), capDrop...),
		CapAdd:        append([]string(nil), capAdd...),
	}
	// plan-6 (M3): a dataPath is mounted with Mounts (bind): if the folder does not exist (unmounted external
	// disk), Docker fails instead of creating it empty and letting itzg generate a new world. The
	// DATA_ROOT folder is created by the agent: it keeps Binds and the usual hash.
	if s.DataPath != "" {
		host.Mounts = []mount.Mount{{Type: mount.TypeBind, Source: dataDir, Target: "/data"}}
	} else {
		host.Binds = []string{dataDir + ":/data"}
	}
	pids := int64(PidsLimit)
	host.Resources.PidsLimit = &pids
	// Validate already checked both sizes.
	if s.Resources.MemLimit != "" {
		host.Resources.Memory, _ = units.RAMInBytes(s.Resources.MemLimit)
	} else {
		mem, _ := units.RAMInBytes(s.Memory)
		host.Resources.Memory = mem + memHeadroom
	}
	if s.Resources.Cpus > 0 {
		host.Resources.NanoCPUs = int64(s.Resources.Cpus * 1e9)
	}
	net := &network.NetworkingConfig{EndpointsConfig: map[string]*network.EndpointSettings{networkName: {}}}
	// plan-8: mc-router labels; they go into the hash with the rest (hashInput.Labels).
	s.Router.addLabels(cfg.Labels, networkName)

	hash, err := hashOf(name, networkName, cfg, host)
	if err != nil {
		return nil, err
	}
	cfg.Labels[LabelHash] = hash
	cfg.Labels[LabelVersion] = strconv.FormatUint(meta.Version, 10)

	return &Build{Name: name, Config: cfg, HostConfig: host, Networking: net, DataDir: dataDir, Hash: hash}, nil
}

func (s Spec) envList() []string {
	m := map[string]string{
		"EULA":          "TRUE",
		"TYPE":          s.Type,
		"VERSION":       s.Version,
		"MEMORY":        s.Memory,
		"ENABLE_RCON":   "true",
		"RCON_PASSWORD": s.RconPassword,
		"RCON_PORT":     strconv.Itoa(RconPort),
		"SERVER_PORT":   strconv.Itoa(GamePort),
	}
	if len(s.Properties) > 0 {
		keys := make([]string, 0, len(s.Properties))
		for k := range s.Properties {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		lines := make([]string, 0, len(keys))
		for _, k := range keys {
			lines = append(lines, k+"="+s.Properties[k])
		}
		m["CUSTOM_SERVER_PROPERTIES"] = strings.Join(lines, "\n")
	}
	// ── plan-2 ──
	// ── plan-3 ──
	s.contentEnv(m)
	// ── plan-4 ──
	// ── plan-5 ──
	// ── plan-6 ──
	// ── plan-7 ──
	// ── plan-8 ──
	// ── plan-9 ──
	// ── plan-10 ──
	s.buildEnvVars(m)
	for k, v := range s.Env {
		m[k] = v
	}
	out := make([]string, 0, len(m))
	for k, v := range m {
		out = append(out, k+"="+v)
	}
	sort.Strings(out)
	return out
}

// hashSchema versions the canonical form of hashInput. Changing it (or changing what
// BuildContainer produces) alters the hash of ALL servers, and the agent recreates
// all containers when updated: only on purpose.
const hashSchema = 1

// hashInput is the canonical, stable form of what defines the container. The JSON of moby's
// types is not used: a new version of the library (new fields or default values)
// would change everything's hash. Rules: everything BuildContainer puts
// in Config/HostConfig/network must be here, and new fields carry omitempty so that,
// when empty, they leave the hash the same.
type hashInput struct {
	Schema      int               `json:"schema"`
	Name        string            `json:"name"`
	Image       string            `json:"image"`
	Env         []string          `json:"env"`
	Tty         bool              `json:"tty"`
	OpenStdin   bool              `json:"openStdin"`
	Labels      map[string]string `json:"labels"` // identity; without hash or version
	Ports       []string          `json:"ports"`  // "25565/tcp->:25570", sorted
	Binds       []string          `json:"binds"`
	Mounts      []string          `json:"mounts,omitempty"` // plan-6: "type:source:destination:ro", sorted
	Network     string            `json:"network"`
	Restart     string            `json:"restart"`
	Memory      int64             `json:"memory"`
	NanoCPUs    int64             `json:"nanoCpus"`
	PidsLimit   int64             `json:"pidsLimit"`
	SecurityOpt []string          `json:"securityOpt"`
	CapDrop     []string          `json:"capDrop"`
	CapAdd      []string          `json:"capAdd"`
}

func hashOf(name, networkName string, cfg *container.Config, host *container.HostConfig) (string, error) {
	in := hashInput{
		Schema: hashSchema, Name: name, Image: cfg.Image, Env: sortedCopy(cfg.Env),
		Tty: cfg.Tty, OpenStdin: cfg.OpenStdin, Labels: map[string]string{},
		Binds: sortedCopy(host.Binds), Network: networkName, Restart: string(host.RestartPolicy.Name),
		Memory: host.Resources.Memory, NanoCPUs: host.Resources.NanoCPUs,
		SecurityOpt: sortedCopy(host.SecurityOpt), CapDrop: sortedCopy(host.CapDrop), CapAdd: sortedCopy(host.CapAdd),
	}
	for k, v := range cfg.Labels {
		if k != LabelHash && k != LabelVersion {
			in.Labels[k] = v
		}
	}
	for p, binds := range host.PortBindings {
		for _, b := range binds {
			ip := ""
			if b.HostIP.IsValid() {
				ip = b.HostIP.String()
			}
			in.Ports = append(in.Ports, p.String()+"->"+ip+":"+b.HostPort)
		}
	}
	sort.Strings(in.Ports)
	for _, m := range host.Mounts {
		in.Mounts = append(in.Mounts, fmt.Sprintf("%s:%s:%s:%t", m.Type, m.Source, m.Target, m.ReadOnly))
	}
	sort.Strings(in.Mounts)
	if host.Resources.PidsLimit != nil {
		in.PidsLimit = *host.Resources.PidsLimit
	}
	b, err := json.Marshal(in) // encoding/json sorts map keys
	if err != nil {
		return "", fmt.Errorf("spec: compute the container hash: %w", err)
	}
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])[:16], nil
}

func sortedCopy(in []string) []string {
	out := append([]string{}, in...)
	sort.Strings(out)
	return out
}

func mustPort(s string) network.Port { return network.MustParsePort(s) }
