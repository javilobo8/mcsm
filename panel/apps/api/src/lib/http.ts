import type { FastifyError, FastifyInstance, FastifyReply, FastifyRequest } from "fastify";
import { z } from "zod";
import { AgentError } from "../agents/hub.js";
import { AgentErrorCode } from "../agents/error-codes.js";

/**
 * HTTP error with a user-facing message (in English). The global handler responds
 * `{ error: message }` with `status`, except 500, which always comes out as "Internal error".
 */
export class HttpError extends Error {
  constructor(public status: number, message: string) { super(message); this.name = "HttpError"; }
}

/** Agent code (or AgentConn local) → HTTP status. Anything not listed here: 502. */
const STATUS_BY_CODE: Record<string, number> = {
  [AgentErrorCode.InvalidSpec]: 400,
  [AgentErrorCode.InvalidRequest]: 400,
  [AgentErrorCode.UnknownServer]: 404,
  [AgentErrorCode.NotFound]: 404,
  [AgentErrorCode.Busy]: 409,
  [AgentErrorCode.Exists]: 409,
  [AgentErrorCode.Disconnected]: 409,
  [AgentErrorCode.Syncing]: 409,
  [AgentErrorCode.Unsupported]: 409,
  [AgentErrorCode.TooLarge]: 413,
  [AgentErrorCode.Timeout]: 504,
  // Files (Plan 5): invalid paths or of the wrong type.
  [AgentErrorCode.InvalidPath]: 400,
  [AgentErrorCode.PathOutside]: 400,
  [AgentErrorCode.Root]: 400,
  [AgentErrorCode.IsDir]: 400,
  [AgentErrorCode.NotDir]: 400,
  [AgentErrorCode.TransferFailed]: 502,
  [AgentErrorCode.IoError]: 502,
  // Import (Plan 6): server with its data outside DATA_ROOT.
  [AgentErrorCode.ExternalData]: 409,
};

/**
 * Translates a failure of a request to the agent into an HttpError. Keeps the text from the agent or
 * Docker (spec §10) except for `unsupported`, which explains that the agent is out of date.
 * An HttpError passes through as is; anything else is 502 with `fallback`.
 */
export function agentErrorToHttp(e: unknown, fallback = "Failed to communicate with the agent"): HttpError {
  if (e instanceof HttpError) return e;
  if (!(e instanceof AgentError)) return new HttpError(502, fallback);
  if (e.code === AgentErrorCode.Unsupported) {
    return new HttpError(409, "The node's agent is out of date and does not understand this command: update it");
  }
  return new HttpError(STATUS_BY_CODE[e.code] ?? 502, e.message || fallback);
}

/** Messages for the 4xx generated by Fastify or its plugins (they come in English). */
const GENERIC_4XX: Record<number, string> = {
  400: "Invalid request",
  401: "No autenticado",
  403: "Forbidden",
  404: "Not found",
  405: "Method not allowed",
  413: "The request is too large",
  415: "Unsupported content type",
  429: "Too many requests: wait a moment and try again",
};

/**
 * Global error handler (registered in buildApp before any plugin, so every route
 * inherits it). Single format `{ error: "…" }`:
 * - HttpError: its status and its message (500 → "Internal error").
 * - AgentError: `agentErrorToHttp` (502 with the agent's text).
 * - ZodError: 400 with the first message.
 * - Fastify and plugin 4xx errors: generic message in English per status.
 * - Anything else: logged and returned as 500 "Internal error", without leaking details.
 */
export function errorHandler(app: FastifyInstance) {
  return (err: FastifyError | Error, req: FastifyRequest, reply: FastifyReply) => {
    const e = err instanceof AgentError ? agentErrorToHttp(err) : err;
    if (e instanceof HttpError) {
      if (e.status >= 500 && e.status !== 502 && e.status !== 504) {
        req.log.error({ err }, "internal error");
        return reply.code(500).send({ error: "Internal error" });
      }
      return reply.code(e.status).send({ error: e.message });
    }
    if (e instanceof z.ZodError) return reply.code(400).send({ error: e.issues[0]?.message ?? "Invalid data" });
    const status = (e as FastifyError).statusCode;
    if (status === undefined || status >= 500 || status < 400) {
      app.log.error({ err }, "internal error");
      return reply.code(500).send({ error: "Internal error" });
    }
    return reply.code(status).send({ error: GENERIC_4XX[status] ?? "Request rejected" });
  };
}
